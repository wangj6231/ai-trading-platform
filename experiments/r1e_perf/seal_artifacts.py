"""Seal newly generated preparation/performance evidence; never overwrite R1."""
from datetime import UTC, datetime
from pathlib import Path

import measure


def main():
    prep = measure.prepared
    root = measure.ROOT
    work = Path(__file__).resolve().parent
    prepared_state = prep.read_json(root / "experiments/r1e/prepared.json")
    run = root / "experiments/baseline" / prepared_state["run_identity_hash"]
    measure.source_guard(run)
    paths = []
    for directory in (root / "experiments/r1e", work, run):
        paths.extend(path for path in directory.rglob("*")
                     if path.is_file() and "__pycache__" not in path.parts
                     and path != work / "artifact_manifest.json")
    hashes = {path.relative_to(root).as_posix(): prep.file_hash(path)
              for path in sorted(paths)}
    manifest = {
        "schema_version": "R1E_PERFORMANCE_ARTIFACTS_V1", "sealed_at": datetime.now(UTC),
        "note": "Preparation and performance evidence only; no official R1-E results. Excludes self and generated bytecode.",
        "official_r1e_state": "DATA_PREPARED_NOT_EXECUTED",
        "q1_run_identity_hash": prepared_state["run_identity_hash"],
        "artifact_count": len(hashes), "artifacts_sha256": hashes,
        "r1_preservation": prep.verify_r1(),
    }
    prep.write_new(work / "artifact_manifest.json", manifest)
    for name, digest in prep.read_json(work / "artifact_manifest.json")["artifacts_sha256"].items():
        if prep.file_hash(root / name) != digest:
            raise RuntimeError(f"New artifact changed during seal: {name}")
    print(prep.encoded({"artifacts_verified": len(hashes), "r1": prep.verify_r1(),
                        "manifest_sha256": prep.file_hash(work / "artifact_manifest.json")}).decode(), flush=True)


if __name__ == "__main__":
    main()
